def real_daily_bars(end: str | None = "2026-07-31") -> list[Bar]:
    """Real daily bars. `end` truncates the series (default: end of July)."""
    out: list[Bar] = []
    for d, o, h, l, c in REAL_DAILY:
        if end and d > end:
            continue
        y, m, dd = (int(x) for x in d.split("-"))
        b = Bar(ts=datetime(y, m, dd, 0, 0, tzinfo=UTC),
                open=o, high=h, low=l, close=c, volume=0.0)
        b.validate()
        out.append(b)
    return out


def split_info(test_month: str = "2026-07") -> dict:
    train = [r for r in REAL_DAILY if r[0] < f"{test_month}-01"]
    test = [r for r in REAL_DAILY if r[0].startswith(test_month)]
    return {
        "train_days": len(train),
        "train_start": train[0][0] if train else None,
        "train_end": train[-1][0] if train else None,
        "train_price_range": (min(r[3] for r in train), max(r[2] for r in train))
        if train else None,
        "test_days": len(test),
        "test_start": test[0][0] if test else None,
        "test_end": test[-1][0] if test else None,
        "test_price_range": (min(r[3] for r in test), max(r[2] for r in test))
        if test else None,
    }
